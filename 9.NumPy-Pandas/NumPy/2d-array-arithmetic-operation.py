# PROGRAM 2: ARITHMETIC OPERATIONS ON 2D ARRAYS

import numpy as np

# Creating two 2D arrays
A = np.array([
    [10, 20],
    [30, 40]
])

B = np.array([
    [5, 10],
    [15, 20]
])

print("ARRAY A:")
print(A)

print("\nARRAY B:")
print(B)

# Addition
print("\nADDITION:")
print(A + B)

# Subtraction
print("\nSUBTRACTION:")
print(A - B)

# Multiplication
print("\nMULTIPLICATION:")
print(A * B)

# Division
print("\nDIVISION:")
print(A / B)

# Modulus
print("\nMODULUS:")
print(A % B)